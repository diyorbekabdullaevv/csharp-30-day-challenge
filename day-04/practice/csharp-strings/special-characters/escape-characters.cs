using System;

namespace Day04
{
  class Program
  {
    static void Main(string[] args)
    {
      // Uses \n to create a new line
      Console.WriteLine("Hello\nWorld");

      // Uses \t to add a tab
      Console.WriteLine("Hello\tWorld");

      // Uses \b for backspace
      Console.WriteLine("Helloo\b World");

      // Uses \\ to print a backslash
      Console.WriteLine("C:\\Users\\Diyorbek");
    }
  }
}
