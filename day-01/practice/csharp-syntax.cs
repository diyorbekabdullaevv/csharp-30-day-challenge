using System;

namespace HelloWorld
{
  class Program
  {
    static void Main(string[] args)
    {
      Console.WriteLine("Hello World!");
    }
  }
}

/* using System; → Gives access to System classes like Console.
namespace HelloWorld → Organizes the code.
class Program → Creates a class called Program.
static → The method belongs to the class itself.
void → The method doesn't return a value.
Main() → The starting point of the program.
string[] args → Stores arguments passed to the program.
Console.WriteLine() → Prints text to the console.
"Hello World!" → The text being printed.
{ } → Defines the beginning and end of code blocks.
; → Marks the end of a statement. */
